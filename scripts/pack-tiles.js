#!/usr/bin/env node
/* ============================================================
 * EdgeOne 构建期瓦片分包脚本（scripts/pack-tiles.js）
 * ------------------------------------------------------------
 * 背景：
 *   1. app/assets/tiles/ 下共 10,096 张 .webp 瓦片（41.1 MB），直接部署会触发
 *      EdgeOne 单项目累计 20,000 文件数上限，导致无法持续更新部署。
 *   2. EdgeOne 单文件大小上限 25 MB，不能简单合成单个 41 MB 文件。
 *
 * 方案（高低阶分离 + 6 分包）：
 *   - z1 ~ z3（共 56 张，0.23 MB）：保留原始 .webp 散图，首屏（z2 16 张）直出零等待。
 *   - z4 ~ z5（共 600 张，3.18 MB）：合并为 tiles_z4_5.pack（1 个文件）。
 *   - z6（共 1,920 张，8.99 MB）：合并为 tiles_z6.pack（1 个文件）。
 *   - z7（共 7,520 张，28.67 MB）：均分为 tiles_z7_0..3.pack（4 个文件，每个约 7.2 MB）。
 *   - 生成索引文件 app/assets/tiles/tiles_idx.js（映射 key -> [packIdx, offset, length]）。
 *
 * 参数：
 *   - 默认（无参，EdgeOne 编译命令 `node scripts/pack-tiles.js`）：
 *       生成 .pack 与 tiles_idx.js，并删除已打包的 z4~z7 散装 .webp（减少 10,040 个文件）。
 *   - `--keep-raw`：本地测试用，生成 .pack 与 tiles_idx.js 但保留原 .webp 文件。
 *   - `--clean`：清理本地生成的 .pack 与 tiles_idx.js。
 * ============================================================ */
'use strict';

const fs = require('fs');
const path = require('path');

const tilesDir = path.resolve(__dirname, '..', 'app', 'assets', 'tiles');
const args = new Set(process.argv.slice(2));
const keepRaw = args.has('--keep-raw');
const cleanOnly = args.has('--clean');

const PACK_NAMES = [
  'tiles_z4_5.pack',
  'tiles_z6.pack',
  'tiles_z7_0.pack',
  'tiles_z7_1.pack',
  'tiles_z7_2.pack',
  'tiles_z7_3.pack'
];
const IDX_FILE = 'tiles_idx.js';

if (!fs.existsSync(tilesDir)) {
  console.log('[pack-tiles] 目录不存在，跳过:', tilesDir);
  process.exit(0);
}

if (cleanOnly) {
  for (const name of [...PACK_NAMES, IDX_FILE]) {
    const p = path.join(tilesDir, name);
    if (fs.existsSync(p)) fs.rmSync(p, { force: true });
  }
  console.log('[pack-tiles] 已清理本地生成的 .pack 与 tiles_idx.js');
  process.exit(0);
}

const allFiles = fs.readdirSync(tilesDir).filter(f => /^\d+_\d+_\d+\.webp$/.test(f));
if (allFiles.length === 0) {
  console.log('[pack-tiles] 未发现散装 .webp 瓦片，跳过打包');
  process.exit(0);
}

const parsed = allFiles.map(file => {
  const key = file.slice(0, -5); // 去掉 .webp
  const [z, x, y] = key.split('_').map(Number);
  return { file, key, z, x, y };
}).sort((a, b) => a.z - b.z || a.x - b.x || a.y - b.y);

const buckets = [[], [], [], [], [], []];
const z7List = parsed.filter(t => t.z === 7);
const z7Quarter = Math.ceil(z7List.length / 4);

let z7Idx = 0;
let keptLowZoom = 0;
for (const item of parsed) {
  if (item.z <= 3) {
    keptLowZoom++;
    continue;
  }
  if (item.z === 4 || item.z === 5) {
    buckets[0].push(item);
  } else if (item.z === 6) {
    buckets[1].push(item);
  } else if (item.z === 7) {
    const b = 2 + Math.min(3, Math.floor(z7Idx / z7Quarter));
    buckets[b].push(item);
    z7Idx++;
  }
}

const idxMap = {};
let packedCount = 0;
let removedCount = 0;

for (let pIdx = 0; pIdx < PACK_NAMES.length; pIdx++) {
  const list = buckets[pIdx];
  const packName = PACK_NAMES[pIdx];
  const packPath = path.join(tilesDir, packName);
  const chunks = [];
  let offset = 0;

  for (const item of list) {
    const fullPath = path.join(tilesDir, item.file);
    const buf = fs.readFileSync(fullPath);
    const len = buf.length;
    chunks.push(buf);
    idxMap[item.key] = [pIdx, offset, len];
    offset += len;
    packedCount++;
  }

  const outBuf = Buffer.concat(chunks, offset);
  fs.writeFileSync(packPath, outBuf);
  console.log(`[pack-tiles] 生成 ${packName}: ${list.length} 张, ${(offset / 1048576).toFixed(2)} MB`);

  if (!keepRaw) {
    for (const item of list) {
      fs.unlinkSync(path.join(tilesDir, item.file));
      removedCount++;
    }
  }
}

const idxContent = '/* Auto-generated by scripts/pack-tiles.js */\n' +
  'window.BOTW_TILES_PACK=' + JSON.stringify({ packs: PACK_NAMES, idx: idxMap }) + ';\n';
const idxPath = path.join(tilesDir, IDX_FILE);
fs.writeFileSync(idxPath, idxContent, 'utf8');

console.log(
  `[pack-tiles] 完成: 保留 z1~z3 散图 ${keptLowZoom} 张, 打包 z4~z7 共 ${packedCount} 张 -> ${PACK_NAMES.length} 个分包 + ${IDX_FILE} (${(Buffer.byteLength(idxContent) / 1024).toFixed(1)} KB)` +
  (keepRaw ? ' [保留原文件模式]' : `, 已移除散图 ${removedCount} 张`)
);
